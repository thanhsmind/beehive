fn queen_bench_bin() -> PathBuf {
    let mut dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    for _ in 0..12 {
        let candidate = dir.join("crates").join("target").join("debug").join(if cfg!(windows) {
            "queen-bench.exe"
        } else {
            "queen-bench"
        });
        if candidate.exists() {
            return candidate;
        }
        if !dir.pop() {
            break;
        }
    }
    panic!(
        "status_readers_a: could not locate a prebuilt queen-bench binary walking ancestors from {} \
         — this cell uses the CURRENT compiled queen-bench binary as a fixed fixture-generation artifact \
         (rust-port-19 owns queen-bench/* this wave) rather than rebuilding it itself; build the workspace \
         once (`cargo build --manifest-path crates/Cargo.toml -p queen-bench`) if it is genuinely missing.",
        env!("CARGO_MANIFEST_DIR")
    );
}

