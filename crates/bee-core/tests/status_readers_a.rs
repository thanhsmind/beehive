#[test]
fn status_readers_a_scribing_debt_orphan_sweep_across_features() {
    let dir = tempfile::tempdir().expect("tempdir");
    // Feature "orphan-f": a capped behavior_change cell, no scribing-run
    // evidence anywhere -> orphaned.
    write_cell(
        dir.path(),
        "rp-orphan-1",
        &json!({
            "id": "rp-orphan-1", "feature": "orphan-f", "status": "capped", "deps": [], "files": [],
            "trace": {"behavior_change": true, "capped_at": "2026-01-10T00:00:00.000Z"}
        }),
    );
    // Feature "synced-f": a capped behavior_change cell, WITH a ledger
    // entry after its capped_at -> not orphaned.
    write_cell(
        dir.path(),
        "rp-synced-1",
        &json!({
            "id": "rp-synced-1", "feature": "synced-f", "status": "capped", "deps": [], "files": [],
            "trace": {"behavior_change": true, "capped_at": "2026-01-10T00:00:00.000Z"}
        }),
    );
    write_file(
        &bee_dir(dir.path()).join("logs").join("scribing-runs.jsonl"),
        &format!("{}\n", json!({"ts": "2026-01-11T00:00:00.000Z", "feature": "synced-f", "areas": ["x"]})),
    );
    // Feature "not-behavior-f": capped but NOT a behavior_change cell ->
    // never counted at all.
    write_cell(
        dir.path(),
        "rp-plain-1",
        &json!({
            "id": "rp-plain-1", "feature": "not-behavior-f", "status": "capped", "deps": [], "files": [],
            "trace": {"behavior_change": false, "capped_at": "2026-01-10T00:00:00.000Z"}
        }),
    );

    let rust_global = cells::global_scribing_debt(dir.path());
    let mjs_global = run_oracle("global-scribing-debt", dir.path(), None);
    assert_eq!(rust_global, mjs_global);
    assert_eq!(rust_global["count"], json!(1));
    assert_eq!(rust_global["features"], json!([{"feature": "orphan-f", "cells": ["rp-orphan-1"]}]));

    // scribingDebt(root, {feature: "orphan-f"}) with no sinceTs override
    // derives the same threshold (0, since bestScribingStampMs finds
    // nothing) and reports the same cell as debt.
    let rust_debt = cells::scribing_debt(dir.path(), Some("orphan-f"), None);
    let mjs_debt = run_oracle("scribing-debt", dir.path(), Some(json!({"feature": "orphan-f"})));
    assert_eq!(rust_debt, mjs_debt);
    assert_eq!(rust_debt["cells"], json!(["rp-orphan-1"]));

    // scribingDebt for "synced-f" is empty: the ledger stamp postdates the
    // cell's capped_at.
    let rust_synced = cells::scribing_debt(dir.path(), Some("synced-f"), None);
    let mjs_synced = run_oracle("scribing-debt", dir.path(), Some(json!({"feature": "synced-f"})));
    assert_eq!(rust_synced, mjs_synced);
    assert_eq!(rust_synced["count"], json!(0));

    // An explicit sinceTs override in the far future clears even the
    // orphaned feature's debt.
    let far_future_ms = 4_000_000_000_000i64; // year ~2096, well past capped_at
    let rust_future = cells::scribing_debt(dir.path(), Some("orphan-f"), Some(far_future_ms));
    let mjs_future = run_oracle("scribing-debt", dir.path(), Some(json!({"feature": "orphan-f", "sinceTs": far_future_ms})));
    assert_eq!(rust_future, mjs_future);
    assert_eq!(rust_future["count"], json!(0));
}

