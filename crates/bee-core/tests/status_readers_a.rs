// ─── oracle driver plumbing ─────────────────────────────────────────────

fn oracle_script() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/support/status_readers_a_oracle.mjs")
}

/// Runs `status_readers_a_oracle.mjs <op> <root>` with `args` (if any)
/// JSON-encoded on stdin, and parses stdout as JSON. Panics loudly on a
/// non-zero exit or unparseable stdout — an oracle failure is never
/// swallowed into a false pass.
fn run_oracle(op: &str, root: &Path, args: Option<Value>) -> Value {
    let mut cmd = Command::new("node");
    cmd.arg(oracle_script()).arg(op).arg(root);
    cmd.stdin(Stdio::piped());
    cmd.stdout(Stdio::piped());
    cmd.stderr(Stdio::piped());
    let mut child = cmd.spawn().expect("failed to spawn node status_readers_a_oracle driver — is `node` on PATH?");
    {
        let mut stdin = child.stdin.take().expect("child stdin");
        let payload = args.map(|v| v.to_string()).unwrap_or_default();
        stdin.write_all(payload.as_bytes()).expect("write oracle stdin");
    }
    let output = child.wait_with_output().expect("wait for status_readers_a_oracle driver");
    assert!(
        output.status.success(),
        "oracle op {op} exited non-zero — stderr: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let stdout = String::from_utf8_lossy(&output.stdout);
    serde_json::from_str(stdout.trim())
        .unwrap_or_else(|e| panic!("oracle op {op}: could not parse stdout {stdout:?}: {e}"))
}

fn write_file(path: &Path, content: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn bee_dir(root: &Path) -> PathBuf {
    root.join(".bee")
}

