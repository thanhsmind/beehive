//! status-read spine (CONTEXT.md D3/D5): `read_backlog_counts`
//! (`.bee/bin/lib/backlog.mjs` `readBacklogCounts`), `capture_queue`
//! (`.bee/bin/lib/capture.mjs` `captureQueue`), `active_decisions`
//! (`.bee/bin/lib/decisions.mjs` `activeDecisions`), and the cells.mjs
//! status helpers (`archived_totals`, `ready_cells`, `scribing_debt`,
//! `global_scribing_debt`, `tier_mix`, `ceiling_scarcity_warning`). Run via
//! `cargo test --manifest-path crates/Cargo.toml -p bee-core --test
//! status_readers_a` (this cell's own `verify`).
//!
//! ORACLE DISCIPLINE (cell must-have): every reader here is diffed against
//! the REAL, FROZEN mjs module — never this file's author's reading of the
//! mjs source alone — via the file-based node driver
//! `tests/support/status_readers_a_oracle.mjs` (same pattern as
//! `fsutil_oracle.rs`, rust-port-5). Fixtures come from two sources:
//!
//! - a host-real-shaped store, generated by the CURRENT already-built
//!   `queen-bench --generate` binary (rust-port-2/rust-port-19, owned by a
//!   concurrent worker this wave — invoked as a fixed prebuilt artifact,
//!   never rebuilt or edited from here);
//! - hand-written edge fixtures: an empty store, corrupt/truncated jsonl
//!   tails, and unknown-extra-field round-trips.
//!
//! Every path used below is a fresh `tempfile::tempdir()` — never this
//! repo's own live `.bee/` store (prohibition: "tests never touch the live
//! .bee/ store").

