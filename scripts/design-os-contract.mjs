import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";

const [pack, ...rest] = process.argv.slice(2);
const refs = [];
const notForHost = [];
for (let i = 0; i < rest.length; i++) {
  if (rest[i] === "--not-for-host") {
    const [ref, reason] = (rest[++i] ?? "").split("|");
    if (!ref || !reason) fail("--not-for-host needs 'ref|reason'");
    notForHost.push([ref, reason]);
  } else {
    refs.push(rest[i]);
  }
}
if (!pack || refs.length === 0) fail("usage: design-os-contract.mjs <pack> <ref>... [--not-for-host 'ref|reason']... < schema.json");

function fail(message) {
  process.stderr.write(`design-os-contract: ${message}\n`);
  process.exit(1);
}

const schema = JSON.parse(readFileSync(0, "utf8"));
const spoken = (ref) => `ui ${ref.replace(":", " ")}`;

function signatureOf(ref) {
  const [name, sub] = ref.split(":");
  const command = schema.data?.commands?.[name];
  const signature = sub ? command?.subcommands?.[sub] : command?.signature;
  if (!signature) fail(`ui schema has no command '${ref.replace(":", " ")}'`);
  return signature;
}

const out = [
  `# Generated command contract — ${pack}`,
  "",
  "Generated by `scripts/sync-design-os.sh` from the ease-design `schema --json` output. Do not edit: the sync re-renders",
  `this file. These commands add to the core contract while \`${pack}\` is loaded. Flags not listed here do not exist.`,
  "",
];
for (const ref of refs) {
  const sig = signatureOf(ref);
  const positionals = sig.positionals.map((p) => (p.required ? p.name : `[${p.name}]`)).join(" ");
  out.push(`## ${spoken(ref)}`, "", sig.summary, "", `Usage: \`${spoken(ref)}${positionals ? " " + positionals : ""}${sig.flags.length ? " [flags]" : ""}\``, "");
  if (sig.flags.length > 0) {
    out.push("| Flag | Type | Meaning |", "| --- | --- | --- |");
    for (const f of sig.flags) {
      const kind = f.values ? f.values.join("\\|") : f.type;
      out.push(`| \`--${f.name}\`${f.required ? " (required)" : ""} | ${kind} | ${f.summary.replace(/\|/g, "\\|")} |`);
    }
    out.push("");
  }
  out.push(`Error codes: ${sig.errorCodes.map((c) => `\`${c}\``).join(", ") || "none"}`, "");
}
if (notForHost.length > 0) {
  out.push("## Not for host work", "", "This pack's text names these commands. Do not run them in a host.", "");
  for (const [ref, reason] of notForHost) out.push(`- \`${spoken(ref)}\` — ${reason}`);
  out.push("");
}
const body = out.join("\n");
process.stdout.write(`<!-- sha256: ${createHash("sha256").update(body).digest("hex")} -->\n${body}`);
